"""Render docs/outline.md from docs/outline.template.md, filling every number from results/.

Placeholders:
    {{FILE:dot.path:fmt}}   one value from results/FILE.json
        fmt: pct (x100, 2 decimals), pct1, num (2 decimals), num1, num3, num4, int, count, gb, p, str
    {{r2:FILE:dot.path}}    a comparison block as "x% (90% interval a% to b%, p = c, n = d)"
    {{hit:FILE:dot.path}}   a direction block as "x% (90% interval a% to b%), base rate y%, PT p = c, n = d"

Lines between "<!-- if FILE:dot.path == value -->" and "<!-- end -->" are kept only when that
value in results/FILE.json equals the given one; an optional "<!-- else -->" line starts the
alternative. Used for E12, whose numbers exist only if the LLM scorer ran.

Every substitution is also written to results/outline_numbers.csv with its source, so the
brief can be checked against the results files. Run: python -m sentcast.outline
"""
from __future__ import annotations

import csv
import json
import re
from functools import lru_cache

from .config import DRY_RUN, RESULTS, ROOT

TEMPLATE = ROOT / "docs" / "outline.template.md"
OUTPUT = (RESULTS if DRY_RUN else ROOT / "docs") / "outline.md"
PATTERN = re.compile(r"\{\{([^{}]+)\}\}")
BLOCK = re.compile(r"^<!-- if (\w+):([\w.]+) == (\S+) -->\n(.*?)(?:^<!-- else -->\n(.*?))?^<!-- end -->\n", re.S | re.M)


@lru_cache(maxsize=None)
def _file(name: str) -> dict:
    with open(RESULTS / f"{name}.json", encoding="utf-8") as fh:
        return json.load(fh)


def _get(name: str, path: str):
    node = _file(name)
    for key in path.split("."):
        if isinstance(node, list):
            node = node[int(key)]
        else:
            node = node[key]
    return node


def _fmt(x, fmt: str) -> str:
    if x is None:
        return "n/a"
    if fmt == "str":
        return str(x)
    if fmt == "int":
        return f"{int(round(x)):,}"
    if fmt == "count":                      # a median of counts can end in .5; never round it away
        return f"{int(x):,}" if float(x) == int(x) else f"{x:,.1f}"
    if fmt == "gb":
        return f"{x / 1e9:.1f}"
    if fmt == "p":
        return "<0.001" if x < 0.001 else f"{x:.3f}"
    if fmt == "pct":
        return f"{100 * x:.2f}"
    if fmt == "pct1":
        return f"{100 * x:.1f}"
    if fmt in ("num", "num3", "num4", "num1"):
        return f"{x:.{ {'num': 2, 'num3': 3, 'num4': 4, 'num1': 1}[fmt] }f}"
    raise ValueError(f"unknown format {fmt!r}")


def _r2(block: dict) -> str:
    if not isinstance(block, dict) or "r2_os" not in block:
        return "n/a"
    return (f"{_fmt(block['r2_os'], 'pct')}% (90% interval {_fmt(block['r2_ci_lo'], 'pct')}% to "
            f"{_fmt(block['r2_ci_hi'], 'pct')}%, p = {_fmt(block.get('p'), 'p')}, n = {block['n_oos']})")


def _hit(block: dict) -> str:
    if not isinstance(block, dict) or "hit_rate" not in block:
        return "n/a"
    return (f"{_fmt(block['hit_rate'], 'pct1')}% (90% interval {_fmt(block['hit_ci_lo'], 'pct1')}% to "
            f"{_fmt(block['hit_ci_hi'], 'pct1')}%), base rate {_fmt(block['hit_rate_base'], 'pct1')}%, "
            f"PT p = {_fmt(block.get('pt_p'), 'p')}, n = {block['n_oos']}")


def _select(m: re.Match) -> str:
    """Keep the first or the second part of a conditional block, by a value in results/."""
    name, path, want, yes, no = m.groups()
    try:
        value = str(_get(name, path))
    except (KeyError, IndexError, FileNotFoundError, TypeError):
        if not DRY_RUN:
            raise
        value = None
    return yes if value == want else (no or "")


def render(template: str) -> tuple[str, list[dict]]:
    used: list[dict] = []
    template = BLOCK.sub(_select, template)

    def sub(m: re.Match) -> str:
        parts = m.group(1).split(":")
        try:
            if parts[0] in ("r2", "hit"):
                kind, name, path = parts
                value = (_r2 if kind == "r2" else _hit)(_get(name, path))
            else:
                name, path, fmt = parts
                kind = fmt
                value = _fmt(_get(name, path), fmt)
        except (KeyError, IndexError, FileNotFoundError, ValueError, TypeError) as exc:
            if DRY_RUN:                      # partial results: show what is missing, keep going
                print(f"unresolved: {m.group(1)} ({type(exc).__name__}: {exc})")
                return f"MISSING({m.group(1)})"
            raise KeyError(f"cannot resolve {{{{{m.group(1)}}}}}: {type(exc).__name__}: {exc}") from exc
        used.append({"placeholder": m.group(1), "file": f"results/{name}.json", "path": path, "format": kind,
                     "rendered": value})
        return value

    return PATTERN.sub(sub, template), used


def main() -> None:
    text, used = render(TEMPLATE.read_text(encoding="utf-8"))
    header = ("<!-- Generated by `python -m sentcast.outline` from docs/outline.template.md. "
              "Edit the template, not this file. -->\n\n")
    OUTPUT.write_text(header + text, encoding="utf-8", newline="\n")
    with open(RESULTS / "outline_numbers.csv", "w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["placeholder", "file", "path", "format", "rendered"], lineterminator="\n")
        w.writeheader()
        w.writerows(used)
    print(f"wrote {OUTPUT} with {len(used)} values from results/")


if __name__ == "__main__":
    main()
